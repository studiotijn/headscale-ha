"""Generate the ACL policy (and the Edgebox firewall) from the multi-tenant model.

Pure functions: the same model and node list always give the same text and hash,
so every applied policy is reproducible and can be compared.

Enforcement layers
------------------
1. Headscale policy (this module): default deny; each node filters what it receives.
   The policy carries a ``tests`` block with the traffic matrix, including the
   isolation invariants. Headscale refuses to load a policy whose tests fail.
2. Route approval: an Edgebox may only offer the VPN subnet of its own location.
3. nftables on the Edgebox (``edge_nftables``): NAT 10.81.<n>.y <-> 172.168.1.y and an
   allowlist for forwarded traffic, independent of layer 1.
"""

from __future__ import annotations

import hashlib
import ipaddress
import json
import re

from . import tenancy as tn

HEADER = (
    "// GENERATED by the Headscale app (multi-tenant mode). Do not edit here:\n"
    "// change the networks, locations and connections in the app's Networks tab.\n"
)
TEST_PORT = 22  # port used for deny tests (no generated grant ever has these sources)
MAX_REPS = 2  # nodes per domain used as test representatives


def _group(domain_id: str) -> str:
    return f"group:dom-{domain_id}"


def _node_alias(node: dict) -> str:
    return f"node-{int(node['id'])}"


def _dev_alias(dev: dict) -> str:
    return f"dev-{dev['id']}"


def _loc_alias(loc: dict) -> str:
    return f"loc-{loc['id']}"


def _slug(text: str) -> str:
    return re.sub(r"[^a-z0-9-]+", "-", text.lower()).strip("-")[:40] or "x"


def _grant_ports(ports: list[str]) -> list[str]:
    """Model ports -> grant 'ip' entries (Headscale/Tailscale syntax)."""
    out = []
    for p in ports:
        if p == "*":
            return ["*"]
        if p == "icmp:*":
            out.append("icmp:*")
        elif ":" in p:
            out.append(p)
        else:
            out.append(p)  # bare port: any protocol
    return out


def _first_port(ports: list[str]) -> tuple[str | None, int | None]:
    """(protocol, port) for a positive test, or (None, None) when no TCP port can be tested."""
    for p in ports:
        if p == "*":
            return "tcp", 443
        proto, _, rng = p.rpartition(":") if ":" in p else ("", "", p)
        if proto in ("", "tcp") and rng != "*" and rng[0].isdigit():
            return "tcp", int(rng.split("-")[0])
        if proto == "tcp" and rng == "*":
            return "tcp", 443
    return None, None


class Context:
    """Live data the generator needs besides the model."""

    def __init__(
        self,
        admin_user: str,
        nodes: list[dict],
        home_routes: list[str] | None = None,
        exit_node: bool = False,
        shared_services: list[dict] | None = None,
        remote_printers: list[dict] | None = None,
    ):
        self.admin_user = admin_user
        self.nodes = sorted(nodes, key=lambda n: int(n["id"]))
        self.nodes_by_id = {int(n["id"]): n for n in self.nodes}
        self.home_routes = sorted({str(ipaddress.ip_network(r, strict=False)) for r in home_routes or []})
        self.exit_node = exit_node
        self.shared_services = shared_services or []
        self.remote_printers = remote_printers or []


def generate(model: dict, ctx: Context) -> dict:
    """Return {"text", "policy", "sha256", "tests", "warnings"}."""
    warnings = tn.validate(model, ctx.nodes, ctx.home_routes)
    home = tn.home_domain(model)
    domains = model["domains"]

    groups: dict[str, list[str]] = {"group:admins": [f"{ctx.admin_user}@"]}
    for d in domains:
        if d.get("users"):
            groups[_group(d["id"])] = [f"{u}@" for u in d["users"]]

    tag_owners: dict[str, list[str]] = {"tag:homerouter": ["group:admins"]}
    for d in domains:
        tag_owners[tn.server_tag(d["id"])] = ["group:admins"]
    for loc in model["locations"]:
        tag_owners[tn.edge_tag(loc)] = ["group:admins"]

    hosts: dict[str, str] = {}
    for i, r in enumerate(ctx.home_routes):
        hosts[f"home-net-{i + 1}"] = r
    for loc in model["locations"]:
        hosts[_loc_alias(loc)] = str(ipaddress.ip_network(loc["vpn_subnet"]))
    for dev in model["devices"]:
        loc = tn.location(model, dev["location"])
        hosts[_dev_alias(dev)] = f"{tn.vpn_ip(loc, dev['ip'])}/32"
    used_nodes: set[int] = set()

    def node_ref(node_id: int) -> str | None:
        node = ctx.nodes_by_id.get(int(node_id))
        ip = tn.node_ipv4(node) if node else None
        if not ip:
            return None
        hosts[_node_alias(node)] = f"{ip}/32"
        used_nodes.add(int(node_id))
        return _node_alias(node)

    auto_routes: dict[str, list[str]] = {r: ["tag:homerouter"] for r in ctx.home_routes} if home else {}
    for loc in model["locations"]:
        auto_routes[str(ipaddress.ip_network(loc["vpn_subnet"]))] = [tn.edge_tag(loc)]
    auto_approvers: dict = {"routes": auto_routes}
    if ctx.exit_node and home:
        auto_approvers["exitNode"] = ["tag:homerouter"]

    grants: list[dict] = []

    # Internal policy per domain ("full": its members reach everything of their own domain).
    for d in domains:
        if d.get("internal") != "full" or not d.get("users"):
            continue
        dst = [_group(d["id"]), tn.server_tag(d["id"])]
        if d.get("home"):
            dst += ["tag:homerouter"] + [f"home-net-{i + 1}" for i in range(len(ctx.home_routes))]
        for loc in model["locations"]:
            if loc["domain"] == d["id"]:
                dst += [_loc_alias(loc), tn.edge_tag(loc)]
        grants.append({"#name": f"{d['name']}: internal", "src": [_group(d["id"])], "dst": dst, "ip": ["*"]})
        if d.get("home") and ctx.exit_node:
            grants.append(
                {
                    "#name": f"{d['name']}: exit node",
                    "src": [_group(d["id"])],
                    "dst": ["autogroup:internet"],
                    "ip": ["*"],
                }
            )

    # Home network features of the app: shares and printers elsewhere stay within the home domain.
    if home and home.get("users"):
        for svc in ctx.shared_services:
            alias = f"hsha-{_slug(svc['slug'])}"
            hosts[alias] = f"{svc['ip']}/32"
            ports = [str(p) for p in svc.get("ports") or []] or ["*"]
            grants.append(
                {
                    "#name": f"Share {svc.get('name') or svc['slug']}",
                    "src": [_group(home["id"])],
                    "dst": [alias],
                    "ip": ["*"] if "*" in ports else [f"tcp:{p}" for p in ports],
                }
            )
        for p in ctx.remote_printers:
            alias = f"prn-{_slug(p['slug'])}"
            hosts[alias] = f"{p['ip']}/32"
            grants.append(
                {
                    "#name": f"Printer {p.get('name') or p['slug']} (elsewhere)",
                    "src": [_group(home["id"])],
                    "dst": [alias],
                    "ip": [f"tcp:{int(p['port'])}"],
                }
            )

    # Explicit connections.
    for c in model["connections"]:
        if not c.get("enabled", True):
            continue
        src = _endpoint(model, c["src"], node_ref, is_src=True)
        dst = _endpoint(model, c["dst"], node_ref, is_src=False)
        if not src or not dst:
            warnings.append(f"Connection {c.get('name') or c['id']} skipped: source or destination has no address")
            continue
        grants.append({"#name": c.get("name") or c["id"], "src": src, "dst": dst, "ip": _grant_ports(c["ports"])})

    for g in model.get("manual_grants", []):
        grants.append({**g, "#name": g.get("#name", "manual")})

    tests = _tests(model, ctx, hosts, node_ref)

    policy = {
        "groups": groups,
        "tagOwners": tag_owners,
        "hosts": dict(sorted(hosts.items())),
        "autoApprovers": auto_approvers,
        "grants": grants,
    }
    if tests:
        policy["tests"] = tests
    body = json.dumps(policy, indent=2, ensure_ascii=False)
    sha = hashlib.sha256(body.encode()).hexdigest()
    text = HEADER + f"// model revision {model.get('revision')}, sha256 {sha[:16]}\n" + body + "\n"
    return {"text": text, "policy": policy, "sha256": sha, "tests": len(tests), "warnings": warnings}


def _endpoint(model: dict, ref: str, node_ref, is_src: bool) -> list[str]:
    kind, _, key = ref.partition(":")
    if kind == "domain":
        d = tn.domain(model, key)
        return [_group(key)] if d and d.get("users") else []
    if kind == "node":
        alias = node_ref(int(key))
        return [alias] if alias else []
    if is_src:
        return []
    if kind == "dev":
        dev = tn.device(model, key)
        return [_dev_alias(dev)] if dev else []
    if kind == "loc":
        loc = tn.location(model, key)
        return [_loc_alias(loc)] if loc else []
    if kind == "edge":
        loc = tn.location(model, key)
        return [tn.edge_tag(loc)] if loc else []
    return []


# ------------------------------------------------------------------ tests
def _reps(model: dict, ctx: Context, domain_id: str, node_ref) -> list[str]:
    """Up to MAX_REPS user-owned or server nodes of a domain (no Edgeboxes), as host aliases."""
    out = []
    for n in ctx.nodes:
        if tn.node_domain(model, n) == domain_id and not tn.node_location(model, n):
            alias = node_ref(int(n["id"]))
            if alias:
                out.append(alias)
        if len(out) >= MAX_REPS:
            break
    return out


def _tests(model: dict, ctx: Context, hosts: dict, node_ref) -> list[dict]:
    tests: list[dict] = []
    reps = {d["id"]: _reps(model, ctx, d["id"], node_ref) for d in model["domains"]}
    loc_points: dict[str, list[str]] = {}
    for loc in model["locations"]:
        pts = []
        edge = tn.edge_node(model, loc, ctx.nodes)
        if edge:
            alias = node_ref(int(edge["id"]))
            if alias:
                pts.append(alias)
        devs = [d for d in model["devices"] if d["location"] == loc["id"]]
        pts += [_dev_alias(d) for d in devs[:2]]
        loc_points[loc["id"]] = pts

    # 1. Locations never start connections: not to other domains, not to other locations.
    for loc in model["locations"]:
        targets = [f"{a}:{TEST_PORT}" for did, rs in reps.items() for a in rs]
        targets += [f"{a}:{TEST_PORT}" for other, pts in loc_points.items() if other != loc["id"] for a in pts]
        for src in loc_points[loc["id"]]:
            if targets:
                tests.append({"src": src, "deny": sorted(set(targets))})

    # 2. Between domains: deny unless the model has a connection from a to b.
    connected = set()
    for c in model["connections"]:
        if c.get("enabled", True):
            src_dom = tn.endpoint_domain(model, c["src"], ctx.nodes_by_id)
            connected.add((src_dom, tn.endpoint_domain(model, c["dst"], ctx.nodes_by_id)))
    for a in model["domains"]:
        for b in model["domains"]:
            if a["id"] == b["id"] or (a["id"], b["id"]) in connected:
                continue
            deny = [f"{x}:{TEST_PORT}" for x in reps[b["id"]]]
            for loc in model["locations"]:
                if loc["domain"] == b["id"]:
                    deny += [f"{p}:{TEST_PORT}" for p in loc_points[loc["id"]]]
            for src in reps[a["id"]]:
                if deny:
                    tests.append({"src": src, "deny": sorted(set(deny))})

    # 3. Every enabled connection with a concrete source and a single-host destination is reachable.
    for c in model["connections"]:
        if not c.get("enabled", True):
            continue
        _proto, port = _first_port(c["ports"])
        if port is None:
            continue
        kind, _, key = c["src"].partition(":")
        srcs = reps.get(key, [])[:1] if kind == "domain" else [a for a in [node_ref(int(key))] if a]
        dkind, _, dkey = c["dst"].partition(":")
        dst = None
        if dkind == "dev":
            dst = _dev_alias(tn.device(model, dkey))
        elif dkind == "node":
            dst = node_ref(int(dkey))
        elif dkind == "edge":
            loc = tn.location(model, dkey)
            edge = tn.edge_node(model, loc, ctx.nodes)
            dst = node_ref(int(edge["id"])) if edge else None
        elif dkind == "loc":
            devs = [d for d in model["devices"] if d["location"] == dkey]
            dst = _dev_alias(devs[0]) if devs else None
        for src in srcs:
            if dst and src != dst:
                tests.append({"src": src, "accept": [f"{dst}:{port}"]})
    return tests


# ------------------------------------------------------------------ Edgebox
def _nft_ports(ports: list[str]) -> list[str]:
    """Model ports -> nftables match fragments (one rule per fragment)."""
    if "*" in ports:
        return [""]
    by_proto: dict[str, list[str]] = {}
    out = []
    for p in ports:
        if p == "icmp:*":
            out.append("meta l4proto icmp")
            continue
        proto, _, rng = p.rpartition(":") if ":" in p else ("", "", p)
        if rng == "*":
            out.append(f"meta l4proto {proto}" if proto else "")
            continue
        by_proto.setdefault(proto, []).append(rng)
    for proto, rngs in sorted(by_proto.items()):
        rset = rngs[0] if len(rngs) == 1 else "{ " + ", ".join(rngs) + " }"
        out.append(f"{proto} dport {rset}" if proto else f"meta l4proto {{ tcp, udp }} th dport {rset}")
    return out


def edge_nftables(model: dict, loc_id: str, ctx: Context, sha: str | None = None) -> str:
    """nftables ruleset for the Edgebox of a location (second, independent enforcement layer)."""
    loc = tn.location(model, loc_id)
    if loc is None:
        raise tn.ModelError(f"Unknown location {loc_id}")
    lan = loc["lan_iface"]
    local = ipaddress.ip_network(loc["local_subnet"])
    vpn = ipaddress.ip_network(loc["vpn_subnet"])
    rules: list[str] = []
    for c in model["connections"]:
        if not c.get("enabled", True):
            continue
        kind, _, key = c["dst"].partition(":")
        if kind == "dev":
            dev = tn.device(model, key)
            if not dev or dev["location"] != loc_id:
                continue
            daddr = dev["ip"]
        elif kind == "loc" and key == loc_id:
            daddr = str(local)
        else:
            continue
        skind, _, skey = c["src"].partition(":")
        if skind == "node":
            node = ctx.nodes_by_id.get(int(skey))
            ip = tn.node_ipv4(node) if node else None
            if not ip:
                continue
            saddr = ip
        else:
            # All users of a domain: their devices as they are now. Download the file again
            # after adding a device for such a user.
            dom = tn.domain(model, skey) or {}
            ips = sorted(
                {tn.node_ipv4(n) for n in ctx.nodes if tn.node_user(n) in dom.get("users", []) and tn.node_ipv4(n)}
            )
            if not ips:
                continue
            saddr = ips[0] if len(ips) == 1 else "{ " + ", ".join(ips) + " }"
        for frag in _nft_ports(c["ports"]):
            match = " ".join(x for x in (f"ip saddr {saddr}", f"ip daddr {daddr}", frag) if x)
            rules.append(f'    iifname "tailscale0" oifname "{lan}" {match} accept  # {c.get("name") or c["id"]}')
    head = [
        f"#!/usr/sbin/nft -f\n# Generated by the Headscale app for location {loc['name']} ({loc_id}),",
        f"# model revision {model.get('revision')}{f', policy {sha[:16]}' if sha else ''}.",
        f"# VPN {vpn} <-> local {local} (1:1, host part unchanged). LAN interface: {lan}",
        "# Install: copy to /etc/hsha-edge.nft, run `nft -f /etc/hsha-edge.nft`, and include it",
        "# from /etc/nftables.conf (or a systemd unit) so it is loaded at boot.",
        "# After revoking access also run: conntrack -D -s 100.64.0.0/10",
        "",
        "table inet hsha_edge",
        "delete table inet hsha_edge",
        "table inet hsha_edge {",
        "  chain prerouting {",
        "    type nat hook prerouting priority dstnat; policy accept;",
        f'    iifname "tailscale0" ip daddr {vpn} dnat ip prefix to ip daddr map {{ {vpn} : {local} }}',
        "  }",
        "  chain forward {",
        "    type filter hook forward priority filter + 10; policy drop;",
        "    ct state established,related accept",
        "    ct state invalid drop",
        *(rules or ["    # no connections to this location: nothing is forwarded"]),
        "  }",
        "  chain postrouting {",
        "    type nat hook postrouting priority srcnat; policy accept;",
        f'    iifname "tailscale0" oifname "{lan}" masquerade',
        "  }",
        "}",
        "",
    ]
    return "\n".join(head)


def edge_up_command(loc: dict, login_server: str, authkey: str = "<KEY>") -> str:
    return (
        f"tailscale up --login-server={login_server} --auth-key={authkey} "
        f"--hostname={loc['domain']}-{loc['id']}-edge "
        f"--advertise-routes={ipaddress.ip_network(loc['vpn_subnet'])} "
        "--accept-routes=false --accept-dns=false"
    )


def matrix(model: dict, ctx: Context) -> dict:
    """Domain x domain overview derived from the model (for the UI)."""
    out: dict[str, dict[str, list[str]]] = {}
    for a in model["domains"]:
        row: dict[str, list[str]] = {}
        for b in model["domains"]:
            if a["id"] == b["id"]:
                row[b["id"]] = ["internal"] if a.get("internal") == "full" else ["explicit"]
                continue
            names = []
            for c in model["connections"]:
                if not c.get("enabled", True):
                    continue
                if (
                    tn.endpoint_domain(model, c["src"], ctx.nodes_by_id) == a["id"]
                    and tn.endpoint_domain(model, c["dst"], ctx.nodes_by_id) == b["id"]
                ):
                    names.append(c.get("name") or c["id"])
            row[b["id"]] = names
        out[a["id"]] = row
    return out
